"""Write theory/generated/symbol_table.tex from theory/symbols.yaml.

The equation sheet inputs the generated table, so the symbol list is never retyped.
Run from the repository root:

    uv run python theory/tools/gen_symbol_table.py
"""

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
THEORY = ROOT / "theory"
OUT = THEORY / "generated" / "symbol_table.tex"

DOMAIN_TITLES = {
    "constants": "Exact SI constants (kept symbolic)",
    "state": "State variables",
    "adhesion": "Adhesion in water (C1)",
    "sequestration": "Sequestration (C2)",
    "supersaturation": "Supersaturation",
    "nucleation": "Nucleation and Young (C3)",
    "accessibility": "Accessibility of the barrier (C3)",
    "conformality": "Conformality (C4)",
    "stability": "Stability (C5)",
    "film": "Insulating film (C4, R-cell)",
}
REGIME = {"R-slurry": "S", "R-cell": "C", "both": "S,C"}


def tex_escape(text):
    text = text.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"), ("$", r"\$")):
        text = text.replace(a, b)
    text = re.sub(r"\bCa2\+", r"Ca\\textsuperscript{2+}", text)
    text = re.sub(r"\bLi\+", r"Li\\textsuperscript{+}", text)
    text = text.replace(">", "$>$").replace("<", "$<$")
    text = re.sub(r"\bCaCO3\b", r"CaCO\\textsubscript{3}", text)
    return text


def tex_unit(unit):
    if unit == "1":
        return "--"
    parts = []
    for tok in unit.split():
        name, _, power = tok.partition("^")
        name = r"\Omega" if name == "Ohm" else r"\mathrm{%s}" % name
        parts.append(name + ("^{%s}" % power if power else ""))
    return "$" + r"\,".join(parts) + "$"


def short(entry):
    if "short" in entry:
        return entry["short"]
    text = entry["meaning"]
    for sep in ("; ", " (", ", "):
        head = text.split(sep)[0]
        if len(head) >= 12:
            text = head
    return text


def main():
    doc = yaml.safe_load((THEORY / "symbols.yaml").read_text(encoding="utf-8"))
    rows, current = [], None
    for e in doc["symbols"]:
        if e["domain"] != current:
            current = e["domain"]
            rows.append(r"\multicolumn{4}{@{}l}{\textit{%s}}\\" % DOMAIN_TITLES[current])
        regimes = ",".join(REGIME[r] for r in e["regimes"])
        rows.append("$%s$ & %s & %s & %s\\\\" % (e["latex"], tex_escape(short(e)), tex_unit(e["unit"]), regimes))
    # two balanced columns, a group heading never left at the foot of a column
    cut = len(rows) // 2
    while rows[cut].startswith(r"\multicolumn") is False and cut > 0 and rows[cut - 1].startswith(r"\multicolumn"):
        cut -= 1
    head = (r"\begin{minipage}[t]{\dimexpr(\textwidth-2mm)/2\relax}\footnotesize\setlength{\tabcolsep}{2pt}"
            r"\begin{tabular}[t]{@{}l p{\dimexpr\linewidth*3/5\relax} l l@{}}\hline"
            "\nSymbol & Meaning & SI unit & Reg.\\\\\\hline\n")
    tail = "\\hline\\end{tabular}\\end{minipage}"
    body = head + "\n".join(rows[:cut]) + "\n" + tail + "\\hfill\n" + head + "\n".join(rows[cut:]) + "\n" + tail + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "% Generated by theory/tools/gen_symbol_table.py from theory/symbols.yaml; do not edit.\n"
        "% Regime column: S = R-slurry, C = R-cell.\n" + body, encoding="utf-8")
    print("wrote %s (%d symbols)" % (OUT.relative_to(ROOT), len(doc["symbols"])))


if __name__ == "__main__":
    main()

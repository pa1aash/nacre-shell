"""Generate figures/blender/elements.yaml (atomic radii for the renderer) from ase.data.

Run in the repository environment: ``uv run python figures/blender/build_elements.py``.
The renderer runs inside the Blender interpreter, which has no ASE, so it reads this file.
Colours are not here; they come from the palette named in figures/blender/render.yaml.
"""
from __future__ import annotations

import importlib.metadata
from pathlib import Path

import yaml
from ase.data import atomic_numbers, covalent_radii, vdw_radii

ELEMENTS = ("H", "C", "N", "O", "Al", "Ca", "Li")
OUT = Path(__file__).with_name("elements.yaml")


def table():
    out = {}
    for el in ELEMENTS:
        z = atomic_numbers[el]
        out[el] = {"Z": z, "covalent": round(float(covalent_radii[z]), 4),
                   "vdw": round(float(vdw_radii[z]), 4)}
    return out


def render():
    doc = {
        "generated_by": "figures/blender/build_elements.py",
        "provenance": {"package": "ase", "version": importlib.metadata.version("ase"),
                       "objects": ["ase.data.covalent_radii", "ase.data.vdw_radii"],
                       "unit": "angstrom"},
        "elements": table(),
    }
    head = "# Generated by figures/blender/build_elements.py; do not edit by hand.\n"
    return head + yaml.safe_dump(doc, sort_keys=False)


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"wrote {OUT}")

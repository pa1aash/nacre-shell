"""The break-even table of the saturated-sink exclusions, generated from the committed break-even file (cp6 F10).

`nacre preprint breakeven-table` reads results/preprint/screen/breakeven_ph/breakeven.csv (lane W4, PH-W4.9), refuses
a file whose sha256 is not the recorded one or whose rows disagree with its provenance, and writes, in
preprint/generated:
  breakeven_table.tex   \\nacreBreakevenTable (Results and Supplementary Information): per phase and cutoff, the
                        headroom E_c - E_ub - m_expt and the break-even ratio r*, the mean-activity ratio of saturated
                        to actual LiClO4 at which the one-sided sink term m_sink uses up the headroom; numbers only as
                        macros, and the one row with negative headroom kept as the file words it;
  breakeven_table.json  the numbers the macros read (the macro block of sources.yaml points here), with the sha256 of
                        each input.
It also rewrites its delimited macro block of sources.yaml. `--check` regenerates in memory and compares byte for byte.
"""
import csv
import hashlib
import io
import json
import re
from pathlib import Path

import yaml

from nacre.preprint import macros, paths
from nacre.preprint.regime_table import Num, tex_of

INPUTS = {
    "breakeven": "results/preprint/screen/breakeven_ph/breakeven.csv",
    "provenance": "results/preprint/screen/breakeven_ph/provenance.json",
}
# sha256 of the break-even file this table was written for (PH-W4.9 report); a new file is a deliberate re-pin
BREAKEVEN_SHA256 = "182dda634eebbcbc22f07bda1203b4bb537689ba200ccd9972333d3a3abc8ce2"
OUT_TEX, OUT_JSON = "breakeven_table.tex", "breakeven_table.json"
JSON_SOURCE = "preprint/generated/breakeven_table.json"
BLOCK_BEGIN = "  # BEGIN breakeven-table macros (generated by `nacre preprint breakeven-table`; do not edit)"
BLOCK_END = "  # END breakeven-table macros"
NOT_EXCLUDED = "not excluded without correction"
COLUMNS = ["phase", "class", "E_c", "E_ub", "m_expt", "headroom_V", "r_star"]

# phase of the file: (table text, macro stem, claim of the ledger)
PHASES = {
    "brushite": ("brushite", "Brushite", "CL-S14"),
    "ACP": ("ACP ($\\beta$-TCP reference)", "Acp", "CL-S14"),
    "HAp": ("HAp", "Hap", "CL-S14"),
    "b-TCP": ("$\\beta$-TCP", "BetaTcp", "CL-S14"),
    "a-TCP": ("$\\alpha$-TCP", "AlphaTcp", "CL-S14"),
    "Ca2SiO4": ("\\ce{Ca2SiO4} (comparator)", "CaSilicate", "CL-S14"),
    "CaCO3": ("calcium carbonate (control)", "Carbonate", "CL-S03"),
}
CLASS_STEM = {"C_mid": "Mid", "C_hi": "Hi"}


class BreakevenTableError(Exception):
    pass


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_inputs(root):
    root = Path(root)
    shas = {k: sha256(root / rel) for k, rel in INPUTS.items()}
    if shas["breakeven"] != BREAKEVEN_SHA256:
        raise BreakevenTableError("%s has sha256 %s, not the recorded %s (re-pin BREAKEVEN_SHA256 deliberately)"
                                  % (INPUTS["breakeven"], shas["breakeven"], BREAKEVEN_SHA256))
    text = (root / INPUTS["breakeven"]).read_text(encoding="utf-8")
    reader = csv.DictReader(io.StringIO(text))
    if reader.fieldnames != COLUMNS:
        raise BreakevenTableError("%s: columns %s, expected %s" % (INPUTS["breakeven"], reader.fieldnames, COLUMNS))
    rows = list(reader)
    prov = json.loads((root / INPUTS["provenance"]).read_text(encoding="utf-8"))
    if prov.get("n_rows") != len(rows):
        raise BreakevenTableError("provenance names %s rows, the file has %d" % (prov.get("n_rows"), len(rows)))
    return {"rows": rows, "edges": prov["edges"]}, shas


def _edge_stem(cls, e_c, edges):
    if cls not in CLASS_STEM or cls not in edges:
        raise BreakevenTableError("class %s has no stem or no edges in the provenance" % cls)
    lo, hi = edges[cls]
    if abs(e_c - lo) < 1e-9:
        return CLASS_STEM[cls] + "Lo"
    if abs(e_c - hi) < 1e-9:
        return CLASS_STEM[cls] + "Up"
    raise BreakevenTableError("cutoff %s V is not an edge of %s %s" % (e_c, cls, edges[cls]))


def _ratio_fmt(v):
    return ".3g" if v < 1000 else "sci:2"


def build_rows(docs):
    """[(phase key, claim, [cells])] in file order; each cell a list of parts."""
    out, seen = [], set()
    for r in docs["rows"]:
        if r["phase"] not in PHASES:
            raise BreakevenTableError("phase %r has no table entry" % r["phase"])
        text, stem, claim = PHASES[r["phase"]]
        e_c, head = float(r["E_c"]), float(r["headroom_V"])
        edge = _edge_stem(r["class"], e_c, docs["edges"])
        if (stem, edge) in seen:
            raise BreakevenTableError("two rows for %s at %s V" % (r["phase"], r["E_c"]))
        seen.add((stem, edge))
        key = "breakeven/%s/%s" % (stem, edge)
        cut = Num("NumBeCut%s" % edge, "breakeven/cutoff/%s" % edge, e_c, ".1f")
        hd = Num("NumBe%s%sHead" % (stem, edge), key + "/headroom_V", head, ".4f")
        if r["r_star"] == NOT_EXCLUDED:
            if head >= 0:
                raise BreakevenTableError("%s at %s V: %r with headroom %s >= 0" % (r["phase"], r["E_c"], NOT_EXCLUDED, head))
            ratio = [NOT_EXCLUDED]
        else:
            try:
                v = float(r["r_star"])
            except ValueError:
                raise BreakevenTableError("%s at %s V: r* %r is neither a number nor %r"
                                          % (r["phase"], r["E_c"], r["r_star"], NOT_EXCLUDED))
            if head < 0 or v < 1:
                raise BreakevenTableError("%s at %s V: r* %s with headroom %s" % (r["phase"], r["E_c"], v, head))
            ratio = [Num("NumBe%s%sRatio" % (stem, edge), key + "/r_star", v, _ratio_fmt(v))]
        out.append((r["phase"], claim, [[text], [cut], [hd], ratio]))
    return out


def collect(built):
    found = {}
    for _phase, claim, cells in built:
        for c in cells:
            for n in c:
                if not isinstance(n, Num):
                    continue
                if n.name in found and (found[n.name][0].key, found[n.name][0].value) != (n.key, n.value):
                    raise BreakevenTableError("macro %s has two meanings" % n.name)
                found.setdefault(n.name, (n, claim))
    return found


def render_tex(shas, built):
    lines = ["%% Generated by `nacre preprint breakeven-table` from %s (sha256 %s). Do not edit."
             % (INPUTS["breakeven"], shas["breakeven"][:12]),
             "% Defines \\nacreBreakevenTable (Results and Supplementary Information). Numbers only as macros.",
             "\\newcommand{\\nacreBreakevenTable}{%",
             "\\begingroup\\footnotesize\\setlength{\\tabcolsep}{4pt}",
             "\\begin{tabular}{lrrl}", "\\toprule",
             "phase & cutoff (V) & headroom (V) & $r^*$ \\\\", "\\midrule"]
    last = None
    for phase, _claim, cells in built:
        if last is not None and phase != last:
            lines.append("\\addlinespace[2pt]")
        row = [tex_of(c) for c in cells]
        if phase == last:
            row[0] = ""
        lines.append(" & ".join(row) + " \\\\")
        last = phase
    lines += ["\\bottomrule", "\\end{tabular}", "\\endgroup", "}"]
    return "\n".join(lines) + "\n"


def render_json(shas, nums):
    tree = {}
    for n, _claim in nums.values():
        node = tree
        parts = n.key.split("/")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = n.value
    out = {"schema": 1, "generator": "nacre preprint breakeven-table",
           "inputs": {INPUTS[k]: shas[k] for k in INPUTS}, "numbers": tree}
    return json.dumps(out, indent=1, sort_keys=True) + "\n"


def macro_block(nums):
    specs = {}
    for name in sorted(nums):
        n, claim = nums[name]
        specs[name] = {"source": JSON_SOURCE, "key": "numbers/" + n.key, "format": n.fmt, "claim": claim}
    text = yaml.safe_dump(specs, sort_keys=False, default_flow_style=False, width=1000)
    body = "".join("  " + ln + "\n" if ln.strip() else ln for ln in text.splitlines(True))
    return BLOCK_BEGIN + "\n" + body + BLOCK_END + "\n"


def splice_block(sources_text, block):
    rx = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END) + r"\n", re.S)
    if rx.search(sources_text):
        return rx.sub(lambda _m: block, sources_text)
    return sources_text.rstrip("\n") + "\n" + block


def generate(root):
    """The outputs as {path: text}, without writing anything."""
    docs, shas = read_inputs(root)
    built = build_rows(docs)
    nums = collect(built)
    existing = macros.load_sources(root)["macros"]
    clash = sorted(n for n in nums if n in existing and existing[n].get("source") != JSON_SOURCE)
    if clash:
        raise BreakevenTableError("macro names already defined by another source: %s" % ", ".join(clash))
    gen = paths.generated(root)
    sources = paths.sources_yaml(root).read_text(encoding="utf-8")
    return {(gen / OUT_TEX): render_tex(shas, built), (gen / OUT_JSON): render_json(shas, nums),
            paths.sources_yaml(root): splice_block(sources, macro_block(nums))}


def write(root):
    out = generate(root)
    for p, text in out.items():
        Path(p).write_text(text, encoding="utf-8", newline="\n")
    return sorted(out)


def check(root):
    """Paths whose committed text differs from a fresh generation (empty means byte-identical)."""
    return [p for p, text in generate(root).items()
            if not Path(p).is_file() or Path(p).read_bytes() != text.encode("utf-8")]

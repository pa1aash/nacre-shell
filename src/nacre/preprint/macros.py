"""Number macros: every number in the paper comes from a result file through sources.yaml.

preprint/generated/sources.yaml maps a macro name to a result JSON file, a key path
inside it, a format and a unit. `nacre preprint macros` writes preprint/generated/numbers.tex
with one \\newcommand per macro and a provenance comment (source path, git blob sha, key).

Mock sources (`mock: true`) are emitted through \\nacreMockNum, which renders a visible
marker in draft mode and stops the build when used in release mode (see nacre-preamble.tex).
numbers.tex does not depend on the build mode, so it can be committed and diffed.
"""
import json
import math
import re
import subprocess
from pathlib import Path

import yaml

from nacre.preprint import paths

NAME_RE = re.compile(r"^Num[A-Z][A-Za-z]*$")
REQUIRED = ("source", "key", "format")


class MacroError(Exception):
    pass


def load_sources(root, path=None):
    path = Path(path) if path else paths.sources_yaml(root)
    if not path.is_file():
        raise MacroError("missing %s" % path)
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    macros = data.get("macros") or {}
    if not isinstance(macros, dict):
        raise MacroError("sources.yaml: `macros` must be a mapping of macro name to spec")
    problems = []
    for name, spec in macros.items():
        if not NAME_RE.match(str(name)):
            problems.append("%s: macro names are letters only and start with Num plus a capital" % name)
            continue
        if not isinstance(spec, dict):
            problems.append("%s: spec must be a mapping" % name)
            continue
        for key in REQUIRED:
            if not spec.get(key):
                problems.append("%s: missing %s" % (name, key))
    if problems:
        raise MacroError("sources.yaml:\n  " + "\n  ".join(problems))
    return data


def mock_names(root, path=None):
    data = load_sources(root, path)
    return sorted(n for n, s in data["macros"].items() if s.get("mock"))


def blob_sha(root, path):
    """The git blob sha of the file's current bytes (git hash-object; works for untracked files)."""
    p = subprocess.run(["git", "-C", str(root), "hash-object", "--", str(path)], capture_output=True, text=True)
    if p.returncode != 0:
        raise MacroError("git hash-object %s failed: %s" % (path, p.stderr.strip()))
    return p.stdout.strip()


def lookup(doc, key):
    """Walk a '/'-separated key path; list items are addressed by integer index."""
    cur = doc
    for part in key.split("/"):
        if isinstance(cur, dict):
            if part not in cur:
                raise KeyError(part)
            cur = cur[part]
        elif isinstance(cur, list):
            try:
                cur = cur[int(part)]
            except (ValueError, IndexError):
                raise KeyError(part)
        else:
            raise KeyError(part)
    return cur


def format_value(value, fmt):
    """Format a number as LaTeX math. `sci:N` gives N decimals times a power of ten."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise MacroError("value %r is not a number" % (value,))
    if isinstance(value, float) and not math.isfinite(value):
        raise MacroError("value %r is not finite" % (value,))
    if fmt.startswith("sci:"):
        digits = int(fmt[4:])
        if value == 0:
            return ("{:.%df}" % digits).format(0.0)
        exp = int(math.floor(math.log10(abs(value))))
        mant = value / 10 ** exp
        if round(abs(mant), digits) >= 10:
            mant, exp = mant / 10, exp + 1
        return ("{:.%df}\\times10^{{%d}}" % (digits, exp)).format(mant)
    try:
        text = ("{:%s}" % fmt).format(value)
    except (ValueError, TypeError) as exc:
        raise MacroError("format %r: %s" % (fmt, exc))
    return text.replace(",", "{,}")


def render(root, sources_path=None):
    """Return the text of numbers.tex. Raises MacroError listing every failing macro."""
    root = Path(root)
    sources_path = Path(sources_path) if sources_path else paths.sources_yaml(root)
    data = load_sources(root, sources_path)
    lines = [
        "%% Generated by `nacre preprint macros` from %s (blob %s). Do not edit."
        % (_rel(root, sources_path), blob_sha(root, sources_path)),
        "% Each macro: source file (repository-relative), its git blob sha, the key path and the format.",
        "% Mock macros render with a visible marker in draft mode and stop a release build when used.",
        "",
    ]
    problems, cache = [], {}
    for name in sorted(data["macros"]):
        spec = data["macros"][name]
        src = root / spec["source"]
        try:
            if src not in cache:
                if not src.is_file():
                    raise MacroError("source file %s not found" % spec["source"])
                cache[src] = (json.loads(src.read_text(encoding="utf-8")), blob_sha(root, src))
            doc, sha = cache[src]
            try:
                value = lookup(doc, spec["key"])
            except KeyError as exc:
                raise MacroError("key %s: no element %s" % (spec["key"], exc))
            text = format_value(value, str(spec["format"]))
        except (MacroError, ValueError) as exc:
            problems.append("%s: %s" % (name, exc))
            continue
        unit = spec.get("unit") or ""
        mock = bool(spec.get("mock"))
        lines.append("%% \\%s%s" % (name, "  [mock]" if mock else ""))
        lines.append("%%   source: %s  blob %s" % (spec["source"], sha))
        lines.append("%%   key: %s  format: %s  unit: %s" % (spec["key"], spec["format"], unit or "none"))
        if mock:
            lines.append("\\newcommand{\\%s}{\\nacreMockNum{%s}{%s}{%s}}" % (name, name, text, unit))
        else:
            lines.append("\\newcommand{\\%s}{\\nacreNum{%s}{%s}}" % (name, text, unit))
        lines.append("")
    if problems:
        raise MacroError("macro generation failed:\n  " + "\n  ".join(problems))
    return "\n".join(lines)


def write(root, out=None, sources_path=None):
    out = Path(out) if out else paths.numbers_tex(root)
    text = render(root, sources_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    return out, text.count("\\newcommand{")


def _rel(root, p):
    try:
        return Path(p).resolve().relative_to(Path(root).resolve()).as_posix()
    except ValueError:
        return str(p)

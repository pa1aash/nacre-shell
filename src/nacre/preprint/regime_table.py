def collect_numbers(docs, cells):
    """All Num objects of the table (labels, headers, cells), by macro name; a name has one key and value."""
    found = {}

    def take(parts):
        for n in nums_of(parts):
            if not n.key:
                continue
            if n.name in found and (found[n.name].key, found[n.name].value) != (n.key, n.value):
                raise RegimeTableError("macro %s has two meanings" % n.name)
            found[n.name] = n

    for c in cells.values():
        take(c.parts)
    for rid, *_ in ROWS:
        take(row_label(rid, docs))
    for parts in header_parts(docs).values():
        take(parts)
    take(region_parts(docs))
    return found



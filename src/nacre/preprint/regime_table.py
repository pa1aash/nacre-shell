def render_csv(docs, shas, cells):
    buf = io.StringIO(newline="")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["row_id", "row_label", "group", "stage_tag", "column", "text", "words", "marker", "note", "numbers",
                "source_files", "source_sha256"])
    group_of = {r[0]: r[1] for r in ROWS}
    tag_of = {r[0]: r[4] for r in ROWS}
    for rid, *_ in ROWS:
        for col in COLUMNS:
            c = cells[(rid, col)]
            text = plain_of(c.parts)
            marker = ALT_B if c.note == ALT_B else ""
            if marker:
                text += " [" + ALT_B + "]"
            w.writerow([rid, plain_label(rid, docs), group_of[rid], tag_of[rid], col, text, "; ".join(c.words), marker,
                        c.note if not marker else "", "; ".join("%s=%s" % (n.name, n.plain()) for n in nums_of(c.parts) if n.key),
                        "; ".join(INPUTS[s] for s in c.sources), "; ".join(shas[s] for s in c.sources)])
    return buf.getvalue()


def render_json(docs, shas, cells):
    nums = collect_numbers(docs, cells, shas)
    tree = {}
    for n in nums.values():
        node = tree
        parts = n.key.split("/")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = n.value
    out = {"schema": 1, "generator": "nacre preprint regime-table",
           "inputs": {INPUTS[k]: shas[k] for k in INPUTS},
           "production_manifest": {"thresholds_hash": docs["films"]["provenance"]["thresholds_hash"],
                                   "params_hash": docs["films"]["provenance"]["prior_file_hash"],
                                   "ladder_hash": docs["films"]["provenance"]["ladder_hash"]},
           "numbers": tree}
    return json.dumps(out, indent=1, sort_keys=True) + "\n", nums


def macro_block(nums):
    specs = {}
    for name in sorted(nums):
        n = nums[name]
        spec = {"source": JSON_SOURCE, "key": "numbers/" + n.key, "format": n.fmt}
        if n.unit:
            spec["unit"] = n.unit
        spec["claim"] = "CL-D04"
        specs[name] = spec
    text = yaml.safe_dump(specs, sort_keys=False, default_flow_style=False, width=1000)
    body = "".join("  " + ln + "\n" if ln.strip() else ln for ln in text.splitlines(True))
    return BLOCK_BEGIN + "\n" + body + BLOCK_END + "\n"


def splice_block(sources_text, block):
    rx = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END) + r"\n", re.S)
    if rx.search(sources_text):
        return rx.sub(lambda _m: block, sources_text)
    return sources_text.rstrip("\n") + "\n" + block


def generate(root):
    """The four outputs as {relative path: text}, without writing anything."""
    docs, shas = read_inputs(root)
    cells = build_cells(docs)
    json_text, nums = render_json(docs, shas, cells)
    # every macro the table uses that is not generated here must already exist in sources.yaml
    existing = macros.load_sources(root)["macros"]
    used = set()
    for c in cells.values():
        used |= {p.name for p in nums_of(c.parts)}
    for parts in list(header_parts(docs).values()) + [region_parts(docs)]:
        used |= {p.name for p in nums_of(parts)}
    missing = sorted(u for u in used if u not in nums and u not in existing)
    if missing:
        raise RegimeTableError("macros the table uses and no source defines: %s" % ", ".join(missing))
    gen = paths.generated(root)
    sources = paths.sources_yaml(root).read_text(encoding="utf-8")
    return {
        (gen / OUT_TEX): render_tex(docs, shas, cells),
        (gen / OUT_CSV): render_csv(docs, shas, cells),
        (gen / OUT_JSON): json_text,
        paths.sources_yaml(root): splice_block(sources, macro_block(nums)),
    }


def write(root):
    out = generate(root)
    for p, text in out.items():
        Path(p).write_text(text, encoding="utf-8", newline="\n")
    return sorted(out)


def check(root):
    """Paths whose committed text differs from a fresh generation (empty means byte-identical)."""
    return [p for p, text in generate(root).items()
            if not Path(p).is_file() or Path(p).read_bytes() != text.encode("utf-8")]

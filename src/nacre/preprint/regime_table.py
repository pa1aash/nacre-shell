def collect_numbers(docs, cells, shas=None):
    """All Num objects of the table (labels, headers, cells, notes, supplementary tables), by macro name; a name has one key and value."""
    found = {}

    def take(parts):
        for n in nums_of(parts):
            if not n.key:
                continue
            if n.name in found and (found[n.name].key, found[n.name].value) != (n.key, n.value):
                raise RegimeTableError("macro %s has two meanings" % n.name)
            found[n.name] = n

    for c in cells.values():
        take(c.parts)
    for rid, *_ in ROWS:
        take(row_label(rid, docs))
    for parts in header_parts(docs).values():
        take(parts)
    take(region_parts(docs))
    for note in notes_parts(docs, shas or {"params": "", "ladder": "", "ladder_sens": ""}):
        take(note)
    for row in perph_rows_parts(docs):
        for c in row:
            take(c if isinstance(c, list) else [c])
    for note in perph_notes(docs) + rerun_notes(docs):
        take(note)
    for row in rerun_rows_parts(docs):
        for c in row:
            take(c if isinstance(c, list) else [c])
    take(list(extra_numbers(docs).values()))
    n = Num("NumRegHighDoseStatements", "dose/high_statements", high_dose_count(cells, perph_rows_parts(docs)), "d")
    found[n.name] = n
    return found


def render_tex(docs, shas, cells):
    head = header_parts(docs)
    lines = ["% Generated by `nacre preprint regime-table` from the hash-pinned ladder and the production outputs. Do not edit.",
             "% The file defines three macros: \\nacreRegimeTable (Results), \\nacreRegimePerPh and \\nacreRegimeReruns (Supplementary Information).",
             "% Sourced dose key for the phosphoric-acid slurry: p_total_slurry_h3po4_window (a gap). The ratio-grid run is session PH-W4.6.",
             "\\newcommand{\\nacreRegimeTable}{%"]
    lines += _begin("")[:1]
    lines += ["\\begin{tabular}{>{\\raggedright\\arraybackslash}p{0.18\\textwidth}l"
              + ">{\\raggedright\\arraybackslash}p{0.17\\textwidth}>{\\raggedright\\arraybackslash}p{0.25\\textwidth}" + ">{\\raggedright\\arraybackslash}p{0.11\\textwidth}" * 3 + "}",
              "\\toprule",
              "row & stage & " + " & ".join(tex_of(head[c]) for c in COLUMNS) + " \\\\"]
    for group, title in GROUPS:
        lines += ["\\midrule", "\\multicolumn{7}{l}{\\emph{%s}} \\\\" % title, "\\addlinespace[2pt]"]
        for rid, g, _l, _p, tag, *_ in ROWS:
            if g != group:
                continue
            cols = [tex_of(cells[(rid, c)].parts) for c in COLUMNS]
            lines.append("%s & %s & %s \\\\" % (tex_of(row_label(rid, docs)), tag, " & ".join(cols)))
    lines += ["\\bottomrule", "\\end{tabular}"]
    lines += _notes_tex(notes_parts(docs, shas)) + ["}", ""]
    lines += ["\\newcommand{\\nacreRegimePerPh}{%"] + _begin("")[:1] + ["\\begin{tabular}{lllllllp{0.12\\textwidth}p{0.12\\textwidth}}", "\\toprule", " & ".join(PERPH_HEAD) + " \\\\", "\\midrule"]
    prows = perph_rows_parts(docs)
    for k, r in enumerate(prows):
        if k and r[0]:
            lines.append("\\addlinespace[2pt]")
        lines.append(_row_tex(r))
    lines += ["\\bottomrule", "\\end{tabular}"] + _notes_tex(perph_notes(docs)) + ["}", ""]
    lines += ["\\newcommand{\\nacreRegimeReruns}{%"] + _begin("")[:1] + ["\\begin{tabular}{lllp{0.2\\textwidth}p{0.2\\textwidth}}", "\\toprule", " & ".join(RERUN_HEAD) + " \\\\", "\\midrule"]
    lines += [_row_tex(r) for r in rerun_rows_parts(docs)]
    lines += ["\\bottomrule", "\\end{tabular}"] + _notes_tex(rerun_notes(docs)) + ["}", ""]
    lines += ["\\newcommand{\\nacreRegimeSensNote}{%", tex_of(sens_note(docs, shas)), "}", ""]
    return "\n".join(lines)


def plain_label(rid, docs):
    for r in ROWS:
        if r[0] == rid:
            return plain_of(row_label(rid, docs)) if rid == "calcite" else r[3]


def render_csv(docs, shas, cells):
    buf = io.StringIO(newline="")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["row_id", "row_label", "group", "stage_tag", "column", "text", "words", "marker", "note", "numbers",
                "source_files", "source_sha256"])
    group_of = {r[0]: r[1] for r in ROWS}
    tag_of = {r[0]: r[4] for r in ROWS}
    for rid, *_ in ROWS:
        for col in COLUMNS:
            c = cells[(rid, col)]
            text = plain_of(c.parts)
            marker = ALT_B if c.note == ALT_B else ""
            if marker:
                text += " [" + ALT_B + "]"
            w.writerow([rid, plain_label(rid, docs), group_of[rid], tag_of[rid], col, text, "; ".join(c.words), marker,
                        c.note if not marker else "", "; ".join("%s=%s" % (n.name, n.plain()) for n in nums_of(c.parts) if n.key),
                        "; ".join(INPUTS[s] for s in c.sources), "; ".join(shas[s] for s in c.sources)])
    return buf.getvalue()


def render_json(docs, shas, cells):
    nums = collect_numbers(docs, cells, shas)
    tree = {}
    for n in nums.values():
        node = tree
        parts = n.key.split("/")
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        node[parts[-1]] = n.value
    out = {"schema": 1, "generator": "nacre preprint regime-table",
           "inputs": {INPUTS[k]: shas[k] for k in INPUTS},
           "production_manifest": {"thresholds_hash": docs["films"]["provenance"]["thresholds_hash"],
                                   "params_hash": docs["films"]["provenance"]["prior_file_hash"],
                                   "ladder_hash": docs["films"]["provenance"]["ladder_hash"]},
           "numbers": tree}
    return json.dumps(out, indent=1, sort_keys=True) + "\n", nums


def macro_block(nums):
    specs = {}
    for name in sorted(nums):
        n = nums[name]
        spec = {"source": JSON_SOURCE, "key": "numbers/" + n.key, "format": n.fmt}
        if n.unit:
            spec["unit"] = n.unit
        spec["claim"] = "CL-D04"
        specs[name] = spec
    text = yaml.safe_dump(specs, sort_keys=False, default_flow_style=False, width=1000)
    body = "".join("  " + ln + "\n" if ln.strip() else ln for ln in text.splitlines(True))
    return BLOCK_BEGIN + "\n" + body + BLOCK_END + "\n"


def splice_block(sources_text, block):
    rx = re.compile(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END) + r"\n", re.S)
    if rx.search(sources_text):
        return rx.sub(lambda _m: block, sources_text)
    return sources_text.rstrip("\n") + "\n" + block


def generate(root):
    """The four outputs as {relative path: text}, without writing anything."""
    docs, shas = read_inputs(root)
    cells = build_cells(docs)
    json_text, nums = render_json(docs, shas, cells)
    # every macro the table uses that is not generated here must already exist in sources.yaml
    existing = macros.load_sources(root)["macros"]
    used = set()
    for c in cells.values():
        used |= {p.name for p in nums_of(c.parts)}
    for parts in list(header_parts(docs).values()) + [region_parts(docs)]:
        used |= {p.name for p in nums_of(parts)}
    missing = sorted(u for u in used if u not in nums and u not in existing)
    if missing:
        raise RegimeTableError("macros the table uses and no source defines: %s" % ", ".join(missing))
    gen = paths.generated(root)
    sources = paths.sources_yaml(root).read_text(encoding="utf-8")
    return {
        (gen / OUT_TEX): render_tex(docs, shas, cells),
        (gen / OUT_CSV): render_csv(docs, shas, cells),
        (gen / OUT_JSON): json_text,
        paths.sources_yaml(root): splice_block(sources, macro_block(nums)),
    }


def write(root):
    out = generate(root)
    for p, text in out.items():
        Path(p).write_text(text, encoding="utf-8", newline="\n")
    return sorted(out)


def check(root):
    """Paths whose committed text differs from a fresh generation (empty means byte-identical)."""
    return [p for p, text in generate(root).items()
            if not Path(p).is_file() or Path(p).read_bytes() != text.encode("utf-8")]

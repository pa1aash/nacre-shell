class Num:
    """A number that reaches the table only through a macro that reads regime_table.json."""

    def __init__(self, name, key, value, fmt, unit="", plain_unit=""):
        self.name, self.key, self.value, self.fmt = name, key, value, fmt
        self.unit, self.plain_unit = unit, plain_unit

    def tex(self):
        return "\\%s{}" % self.name

    def plain(self):
        v, f = self.value, self.fmt
        text = ("{:.%se}" % f[4:]).format(v) if f.startswith("sci:") else (str(v) if f == "text" else ("{:%s}" % f).format(v))
        return text + (" " + self.plain_unit if self.plain_unit else "")


def tex_of(parts):
    return "".join(p.tex() if isinstance(p, Num) else p for p in parts)


def plain_of(parts):
    out = "".join(p.plain() if isinstance(p, Num) else p for p in parts)
    out = out.replace(MARK, "").replace(DISS_MARK, "").replace("\\textsuperscript{b}", " [note b]").replace("$\\beta$", "beta").replace("$\\mathrm{Ca_T}\\ge$", "Ca_T >=").replace("$\\mathrm{Ca_T}$", "Ca_T").replace("$\\mathrm{P_T}$", "P_T")
    out = re.sub(r"\$([A-Za-z]+)_\{?([a-z0-9]+)\}?\$", r"\1\2", out).replace("$", "")
    return " ".join(out.replace("~", " ").split())


def nums_of(parts):
    return [p for p in parts if isinstance(p, Num)]



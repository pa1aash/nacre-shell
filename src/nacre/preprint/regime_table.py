def _row_tex(cells):
    return " & ".join(tex_of(c if isinstance(c, list) else [c]) for c in cells) + " \\\\"


def _begin(cols):
    return ["\\begingroup\\footnotesize\\setlength{\\tabcolsep}{3pt}", "\\begin{tabular}{" + cols + "}", "\\toprule"]


def _notes_tex(notes):
    return ["\\par\\smallskip", "\\begin{minipage}{\\textwidth}\\scriptsize"] + ["%s\\par" % tex_of(n) for n in notes] + ["\\end{minipage}", "\\endgroup"]


def sens_note(docs, shas):
    sens = Num("NumClassSensitivity", "", sensitivity_of(docs["thresholds"])[0], ".1f", "\\mathrm{V}", "V")
    if shas["ladder"] == shas["ladder_sens"]:
        return ["The ladder rebuilt at the sensitivity line of ", sens, " is byte-identical to the nominal ladder, so no verdict changes at ", sens, "."]
    return ["The ladder rebuilt at the sensitivity line of ", sens, " differs from the nominal ladder; the differing entries are printed in the table."]


def high_dose_count(cells, perph_rows):
    n = sum(1 for c in cells.values() if HIGH_TEX in tex_of(c.parts))
    return n + sum(1 for r in perph_rows for i in (8, 12) if r[i] == ["yes"])


def collect_numbers(docs, cells, shas=None):
    """All Num objects of the table (labels, headers, cells, notes, supplementary tables), by macro name; a name has one key and value."""
    found = {}

    def take(parts):
        for n in nums_of(parts):
            if not n.key:
                continue
            if n.name in found and (found[n.name].key, found[n.name].value) != (n.key, n.value):
                raise RegimeTableError("macro %s has two meanings" % n.name)
            found[n.name] = n

    for c in cells.values():
        take(c.parts)
    for rid, *_ in ROWS:
        take(row_label(rid, docs))
    for parts in header_parts(docs).values():
        take(parts)
    take(region_parts(docs))
    for note in notes_parts(docs, shas or {"params": "", "ladder": "", "ladder_sens": ""}):
        take(note)
    for row in perph_rows_parts(docs):
        for c in row:
            take(c if isinstance(c, list) else [c])
    for note in perph_notes(docs) + rerun_notes(docs):
        take(note)
    for row in rerun_rows_parts(docs):
        for c in row:
            take(c if isinstance(c, list) else [c])
    for note in al_salt_notes(docs):
        take(note)
    take(list(extra_numbers(docs).values()))
    n = Num("NumRegHighDoseStatements", "dose/high_statements", high_dose_count(cells, perph_rows_parts(docs)), "d")
    found[n.name] = n
    return found



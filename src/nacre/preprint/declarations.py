"""Generated front and end matter: title, author block, CRediT statement and declarations.

Inputs are never retyped into the manuscript:
  - title          ops/tracks/p0.yaml meta.title_working;
  - author block   ops/tracks/p0_authors.yaml (author order, affiliations, corresponding author);
  - CRediT         the same register (credit_roles), checked against charter/credit_taxonomy.md;
  - declarations   preprint/paper/declarations.yaml (repository, Zenodo DOI, competing
                   interests, funding and compute), filled at W8.5 and C3.

A value that is TBD, or a field marked `<field>_status: to-confirm`, or an author whose status
is not `given`, is wrapped in \\nacrePlaceholder or \\nacrePending. Both render visibly in a
draft build and stop a release build (nacre-preamble.tex); the release guard also refuses them.
"""
import re
from pathlib import Path

import yaml

from nacre.preprint import paths
from nacre.preprint.macros import blob_sha

TBD = "TBD"
_ESC = {"&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "\\": r"\textbackslash{}"}


class DeclarationsError(Exception):
    pass


def esc(text):
    return "".join(_ESC.get(ch, ch) for ch in str(text))


def is_tbd(value):
    return value is None or (isinstance(value, str) and value.strip().upper() == TBD) or value == []


def placeholder(what):
    return "\\nacrePlaceholder{%s}" % esc(what)


def pending(text):
    return "\\nacrePending{%s}" % text


def _letters():
    import string
    for ch in string.ascii_lowercase:
        yield ch


def _header(root, src):
    rel = Path(src).relative_to(root).as_posix()
    return "%% Generated by `nacre preprint declarations` from %s (blob %s). Do not edit.\n" % (
        rel, blob_sha(root, src))


def credit_roles(root):
    """Role names from the fetched taxonomy (the `### <role>` headings)."""
    text = paths.credit_taxonomy(root).read_text(encoding="utf-8")
    part = text.split("## Roles and definitions", 1)[-1]
    return [m.group(1).strip() for m in re.finditer(r"^### (.+)$", part, re.M)]


def load_authors(root, path=None):
    path = Path(path) if path else paths.authors_yaml(root)
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    authors = data.get("authors") or []
    if not authors:
        raise DeclarationsError("%s lists no authors" % path)
    if sum(1 for a in authors if a.get("corresponding")) != 1:
        raise DeclarationsError("exactly one corresponding author is required")
    return authors


def _field(author, name):
    """The LaTeX for one register field: escaped, or a placeholder or pending marker."""
    value = author.get(name)
    if is_tbd(value):
        return placeholder("%s TBD" % name.replace("_", " "))
    text = esc(value)
    if author.get(name + "_status") == "to-confirm":
        return pending(text)
    return text


def author_block(root, path=None):
    path = Path(path) if path else paths.authors_yaml(root)
    authors = load_authors(root, path)
    letters, aff_letter, aff_order = _letters(), {}, []
    names = []
    for a in authors:
        if a.get("status") != "given":
            # the whole entry awaits the operator; one marker covers the name
            name = pending("%s %s" % (esc(a.get("given_name")), esc(a.get("family_name"))))
        else:
            name = "%s %s" % (_field(a, "given_name"), _field(a, "family_name"))
        aff = a.get("affiliation")
        key = TBD + str(len(aff_order)) if is_tbd(aff) else str(aff)
        if key not in aff_letter:
            aff_letter[key] = next(letters)
            aff_order.append((aff_letter[key], _field(a, "affiliation")))
        mark = "\\textit{$^{%s}$}" % aff_letter[key]
        if a.get("corresponding"):
            mark = "$^{\\ast}$" + mark
        names.append(name + mark)
    joined = ", ".join(names[:-1]) + " and " + names[-1] if len(names) > 1 else names[0]
    corr = next(a for a in authors if a.get("corresponding"))
    foot = ["\\footnotetext{\\textit{$^{%s}$~%s}}" % (letter, text) for letter, text in aff_order]
    email = _field(corr, "email")
    foot.append("\\footnotetext{$^{\\ast}$~Corresponding author. E-mail: %s}" % email)
    out = _header(root, path)
    out += "\\newcommand{\\nacreAuthors}{%s}\n" % joined
    out += "\\newcommand{\\nacreAffiliations}{%%\n  %s}\n" % "%\n  ".join(foot)
    return out


def credit_statement(root, path=None):
    path = Path(path) if path else paths.authors_yaml(root)
    authors = load_authors(root, path)
    allowed = set(credit_roles(root))
    parts, problems = [], []
    for a in authors:
        name = "%s %s" % (esc(a.get("given_name")), esc(a.get("family_name")))
        roles = a.get("credit_roles")
        if is_tbd(roles):
            text = placeholder("CRediT roles TBD")
        else:
            roles = [roles] if isinstance(roles, str) else list(roles)
            bad = [r for r in roles if r not in allowed]
            if bad:
                problems.append("%s: roles not in the taxonomy: %s" % (name, ", ".join(bad)))
            text = ", ".join(esc(r) for r in roles)
        parts.append("\\textbf{%s}: %s." % (name, text))
    if problems:
        raise DeclarationsError("CRediT:\n  " + "\n  ".join(problems))
    return _header(root, path) + "\\newcommand{\\nacreCredit}{%%\n  %s}\n" % "\n  ".join(parts)


def front_matter(root):
    path = paths.track_yaml(root)
    meta = (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("meta") or {}
    title = meta.get("title_working")
    text = placeholder("title TBD") if is_tbd(title) else esc(" ".join(str(title).split()))
    return _header(root, path) + "\\newcommand{\\nacreTitle}{%s}\n" % text


DECL_FIELDS = {
    # field: (macro, placeholder text, renderer)
    "repository_url": ("nacreRepoURL", "repository URL, filled at C3", "url"),
    "zenodo_doi": ("nacreZenodoDOI", "Zenodo DOI, filled at C3", "doi"),
    "si_doi": ("nacreSIDOI", "supplementary information DOI, filled at C3", "doi"),
    "competing_interests": ("nacreCompetingInterests", "competing-interests statement, Palaash at W8.5", "text"),
    "funding": ("nacreFunding", "funding statement, Palaash at W8.5", "text"),
    "compute": ("nacreCompute", "compute acknowledgement, Palaash at W8.5", "text"),
}


def declarations(root, path=None):
    path = Path(path) if path else paths.declarations_yaml(root)
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    out = _header(root, path)
    for field, (macro, what, kind) in DECL_FIELDS.items():
        value = data.get(field)
        if is_tbd(value):
            body = placeholder(what)
        elif kind == "url":
            body = "\\url{%s}" % str(value).strip()
        elif kind == "doi":
            doi = str(value).strip()
            body = "\\href{https://doi.org/%s}{%s}" % (doi, esc(doi))
        else:
            body = esc(" ".join(str(value).split()))
        out += "\\newcommand{\\%s}{%s}\n" % (macro, body)
    return out


GENERATED = {
    "front.tex": front_matter,
    "authors.tex": author_block,
    "credit.tex": credit_statement,
    "declarations.tex": declarations,
}


def write_all(root):
    gen = paths.generated(root)
    gen.mkdir(parents=True, exist_ok=True)
    written = []
    for name, fn in GENERATED.items():
        (gen / name).write_text(fn(root), encoding="utf-8", newline="\n")
        written.append(gen / name)
    return written

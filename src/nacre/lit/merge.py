"""Orchestrator merge: thread rows -> lit/evidence_table.csv, lit/corpus/coverage.yaml, lit/corpus/gaps.md."""
import datetime as dt
import re
from pathlib import Path

import yaml

from nacre.lit import evidence as E

GAPS_HEAD = """# Evidence gaps across threads

Generated by `uv run python -m nacre.lit merge` from the thread rows and each thread's `gaps.md`.
Target quantities are ordered by expected physical leverage on the nucleation barrier

    DG*_het = f(theta) * 16 pi gamma_nw^3 v^2 / (3 (k_B T ln S)^2),   cos theta = (gamma_sw - gamma_sn) / gamma_nw

gamma_nw enters cubed (and again through theta); the substrate energies act through f(theta), which
multiplies the whole barrier; the molar volume enters squared; every supersaturation input acts
inside ln S, which enters squared in the denominator; quantities outside the barrier (adhesion,
the in-cell window) come last. A gap is a statement about this search, never a claim that no
evidence exists.
"""


def thread_files(root):
    return [(t, Path(root) / "lit" / "corpus" / t) for t in E.THREADS]


def load_threads(root):
    out, errs = [], []
    patterns = E.scope_patterns(root)
    for t, d in thread_files(root):
        f = d / "rows.csv"
        if not f.exists():
            errs.append("%s: rows.csv missing" % t)
            out.append([])
            continue
        header, rows = E.read_csv(f)
        errs.extend("%s/rows.csv %s" % (t, e) for e in E.validate_rows(rows, header, patterns))
        out.append(rows)
    return out, errs


def _gap_section(path):
    if not path.exists():
        return "(no gaps.md)"
    text = path.read_text(encoding="utf-8").strip()
    return re.sub(r"^#\s.*\n", "", text, count=1).strip()


def write_gaps(root, cov):
    lines = [GAPS_HEAD, "## Target quantities by leverage", "",
             "| rank | target | status | sources | best grade | role in the barrier |",
             "|---|---|---|---|---|---|"]
    for c in sorted(cov, key=lambda c: (c["rank"], c["id"])):
        lines.append("| %d | %s | %s | %d | %s | %s |" % (c["rank"], c["label"], c["status"],
                                                        c["independent_sources"], c["best_grade"] or "-", c["role"]))
    open_ = [c for c in sorted(cov, key=lambda c: (c["rank"], c["id"])) if c["status"] != "covered"]
    lines += ["", "## Open targets (gap or single-source), highest leverage first", ""]
    for c in open_:
        lines.append("- **%s** (%s, rank %d): %s" % (c["label"], c["status"], c["rank"],
                                                     ("rows " + ", ".join(c["row_ids"])) if c["row_ids"] else "no rows"))
    lines += ["", "## Thread gap notes", ""]
    for t, d in thread_files(root):
        lines += ["### %s" % t, "", _gap_section(d / "gaps.md"), ""]
    (Path(root) / "lit" / "corpus" / "gaps.md").write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def run(root):
    root = Path(root)
    per_thread, errs = load_threads(root)
    if errs:
        for e in errs:
            print(e)
        print("merge: %d problem(s) in thread rows; nothing written" % len(errs))
        return 1
    rows, dups = E.merge(per_thread)
    table = root / "lit" / "evidence_table.csv"
    E.write_csv(table, rows)
    final = E.validate_file(table, root)
    cov = E.coverage(rows)
    doc = {
        "generated_utc": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "rule": "covered: >=2 independent sources (distinct DOIs) with numeric rows; single-source: 1; gap: 0",
        "rows": len(rows),
        "duplicates_dropped": [{"dropped": a, "kept": b} for a, b in dups],
        "targets": cov,
    }
    (root / "lit" / "corpus" / "coverage.yaml").write_text(
        yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
    write_gaps(root, cov)
    counts = {s: sum(1 for c in cov if c["status"] == s) for s in ("covered", "single-source", "gap")}
    print("merged %d rows (%d duplicates dropped); validator: %s" % (len(rows), len(dups),
                                                                     "PASS" if not final else "%d problem(s)" % len(final)))
    for e in final:
        print("  " + e)
    print("coverage: %s" % counts)
    return 1 if final else 0

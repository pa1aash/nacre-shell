def _row_cell(p, rid):
    r = p.row(rid)
    val = ("%s %s" % (r["value"], r["unit"])).strip() if r["value"] else r["symbol"]
    return "%s: %s; %s (doi:%s, %s; grade %s)" % (rid, r["quantity"], val, r["doi"], r["locator"], r["grade"])


def markdown(params_sha=PARAMS_SHA):
    p = inputs.Params(inputs.load_snapshot(params_sha, check_git=False))
    lines = [
        "# Anchor DFT protocol",
        "",
        "Generated by `uv run python -m nacre.anchor.protocol` from W1's rows at `%s`." % params_sha,
        "Every error below is read from the fetched row. Lane note N6 applies: the level is justified from",
        "published benchmarks for hydrated Ca2+ with O-donor ligands, not copied from the main study's",
        "periodic-DFT setup.",
        "",
        "**Thermodynamic question.** What is the free energy of replacing first-shell waters of hydrated",
        "Ca2+ by a carboxylate or catecholate ligand in water (src/nacre/anchor/README.md)? This is a",
        "consistency check of the pipeline; W1 rates the experimental comparators single-source.",
        "",
        "| Choice | Chosen | Benchmark rows | Why |",
        "|---|---|---|---|",
    ]
    for name, chosen, rows, why in CHOICES:
        lines.append("| %s | %s | %s | %s |" % (name, chosen, "<br>".join(_row_cell(p, r) for r in rows), why))
    lines += [
        "",
        "## Level used",
        "",
    ]
    for k, v in LEVEL.items():
        lines.append("- `%s`: %s" % (k, v))
    lines += [
        "",
        "## Departures recorded for the local test (P0-W5.2)",
        "",
        "- **Solvent.** The PyPI build of the DFT library (pyscf, pinned in the lane's dependency group) has",
        "  the SMD electrostatics but not its cavity-dispersion-solvent-structure (CDS) term, which needs a",
        "  compile option. The test runs the nearest model, IEF-PCM with the SMD intrinsic radii, and omits",
        "  CDS. For charged clusters the CDS term is a few kcal/mol and partly cancels across the binding",
        "  cycle; the production run (P0-W5.3, Linux pod) either builds the SMD module or records the same",
        "  departure.",
        "- **Dispersion.** The library's dispersion add-on ships Linux wheels only. On this machine the",
        "  D3(BJ) energy, which depends on the geometry alone, comes from the simple-dftd3 program in its",
        "  own pinned environment (`src/nacre/anchor/dftd3_env.yaml`). On the pod the add-on is used.",
        "- **Thermal corrections.** At the GFN2-xTB level, not at the DFT level.",
        "- **Comparators.** `dg_bind_ca_acetate` and `log10_k_ca_carboxylate` are comparators of the test",
        "  only; no parameter is fitted to them.",
        "",
        "Results of the test: `results/preprint/anchor/protocol_test/summary.json` and",
        "`ops/reports/P0-W5.2.md`.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    PROTOCOL_MD.write_text(markdown(), encoding="utf-8")
    print(PROTOCOL_MD.relative_to(REPO).as_posix())
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""The Al-salt ladder as a table input (the template of fig13 is dropped).

Every ladder row whose oxidation reaction has the aluminium perchlorate sink reads undetermined: the
solid-salt budget needs the exchange entropy of Al(ClO4)3 and the ladder has no Gibbs energy of
formation or entropy for it (dfg_al_clo4_3 is a gap; only an enthalpy exists). The CSV carries the
rows as the ladder states them; the booktabs table is generated by lane W8 (preprint/generated).
"""
import csv
import hashlib
import io
import re
from pathlib import Path

from nacre.figs import paths, upstream

SINK = "Al(ClO4)3"
OUT = "al_salt_ladder.csv"
COLUMNS = ("phase", "framing", "reaction_id", "reaction", "sink", "E_ub_V", "E_lb_V", "k1_verdict", "reason",
           "missing_datum", "source_file", "source_sha256")
MISSING = "standard Gibbs energy of formation (or entropy) of solid Al(ClO4)3"


def rows(root):
    key = "ladder_v3"
    e = upstream.entry(key, root)
    doc = upstream.load(key, root)
    out = []
    for r in doc["rows"]:
        if SINK not in r["notes"] or r["framing"] != "crystalline":
            continue
        if r["k1_verdict"] != "undetermined":
            raise ValueError("alsalt: %s %s is %s, not undetermined; the table's premise no longer holds"
                             % (r["phase"], r["reaction_id"], r["k1_verdict"]))
        reaction = r["notes"].rsplit("; ", 1)[-1] if " -> " in r["notes"] else ""
        if r["budget_status"] == "incomplete":
            m = re.search(r"\((no bound on the exchange entropy .*? is a gap\))\)", r["notes"])
            if not m:
                raise ValueError("alsalt: no reason in the notes of %s %s" % (r["phase"], r["reaction_id"]))
            reason = m.group(1)
        else:
            reason = r["budget_status"].replace("symbolic: ", "", 1)
        out.append({"phase": r["phase"], "framing": r["framing"], "reaction_id": r["reaction_id"],
                    "reaction": reaction, "sink": SINK, "E_ub_V": r["E_ub_V"], "E_lb_V": r["E_lb_V"],
                    "k1_verdict": r["k1_verdict"], "reason": reason, "missing_datum": MISSING,
                    "source_file": e["path"], "source_sha256": e["sha256"]})
    if not out:
        raise ValueError("alsalt: no Al-salt rows in the ladder")
    return out


def render(root):
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows(root))
    return buf.getvalue()


def build(root):
    """Write figures/out/tables/al_salt_ladder.csv; return its manifest record."""
    root = Path(root)
    path = paths(root)["out"] / "tables" / OUT
    path.parent.mkdir(parents=True, exist_ok=True)
    text = render(root)
    path.write_text(text)
    return {"path": str(path.relative_to(root)), "sha256": hashlib.sha256(text.encode()).hexdigest(),
            "rows": len(rows(root)), "input": "ladder_v3", "input_sha256": upstream.entry("ladder_v3", root)["sha256"],
            "w8_table_request": "booktabs table of this CSV in preprint/generated (lane W8)"}
